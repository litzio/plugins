
import { readFile, writeFile } from "node:fs/promises";
const base = new URL("./", import.meta.url);
const style = await readFile(new URL("presentation/styles.css", base), "utf8");
const parts = ["workspace", "lifecycle", "trace", "impact", "verification", "assessment", "risks"];
const screen = (await Promise.all(parts.map(name => readFile(new URL("presentation/" + name + ".jsx", base), "utf8")))).join("\n");
await writeFile(new URL("screen.jsx", base), "// Generated by npm run build.\nconst styles = " + JSON.stringify(style) + ";\n" + screen.replaceAll("\r\n", "\n"));
