import { sourceCli } from '../src/cli.mjs';
import { richSample } from '../test/rich-sample.mjs';
import { authoring } from '../src/document.mjs';
import { digest, validate } from '../src/model.mjs';
import { exportReqif } from '../src/reqif.mjs';
import { writeFileSync } from 'node:fs';
import { create } from 'xmlbuilder2';
import assert from 'node:assert/strict';
const [entry, root] = process.argv.slice(2), cli = sourceCli({ entry, root });
const sets = richSample();
sets[0].requirements[0].body = structuredClone(sets[1].requirements[0].body);
sets[0].requirements[0].footnotes = structuredClone(sets[1].requirements[0].footnotes);
sets[0].requirements[0].titleContent = [{ kind: 'text', text: '전압 U' }, { kind: 'subscript', children: [{ kind: 'text', text: 'max' }] }];
for (const [i, s] of sets.entries()) cli.create(s, 'scope-' + i + '.md');
function capture(name) {
  const file = cli.scoped(name + '.md');
  const result = { inspection: cli.run('inspect', file, '--format', 'json'), snapshot: cli.run('compare', file, file, '--json').before };
  writeFileSync(cli.scoped(name + '.json'), JSON.stringify(result, null, 2)); return result;
}
for (let i = 0; i < 2; i++) capture('scope-' + i);
const read = sets.map((_, i) => cli.read('scope-' + i + '.md'));
for (const s of read) for (const r of s.requirements) r.confirmedDigest = digest(r);
assert.deepEqual(validate(read, { formal: true }), []);
const xml = exportReqif(read).xml; writeFileSync(cli.scoped('scoped.reqif'), xml);
const ids = [...create(xml).node.getElementsByTagName('*')].flatMap(n => ['id', 'IDENTIFIER'].filter(a => n.hasAttribute(a)).map(a => n.getAttribute(a)));
console.log('XML IDS', ids.length, new Set(ids).size);
assert.equal(ids.length, new Set(ids).size);
const figure = richSample()[0];
figure.requirements[0].body = [{ kind: 'figure', imageAsset: 'tiny', imageAlt: 'synthetic pixel', caption: [{ kind: 'text', text: '85 °C ' }, { kind: 'strong', children: [{ kind: 'text', text: 'only' }] }] }];
const input = cli.scoped('figure-input.json');
writeFileSync(input, JSON.stringify({ authoring: authoring(figure), images: [{ key: 'tiny', mime: 'image/png', base64: 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9Z1X0AAAAASUVORK5CYII=' }] }));
cli.run('create', cli.scoped('figure.md'), '--input', input, '--format', 'json'); const observed = capture('figure');
const result = cli.read('figure.md'), node = observed.snapshot.blocks.find(b => b.block === 'figure');
assert.deepEqual(result.requirements[0].body[0].caption, node.caption.content);
assert.ok(result.diagnostics.some(d => d.code === 'attachment-required' && d.location[0] === node.path[0]));
assert.throws(() => exportReqif([result], { testOnly: true }), e => e.diagnostics.some(d => d.code === 'attachment-required'));
console.log('PASS actual figure caption object preserved; located attachment diagnostic; all scoped XML IDs unique');
